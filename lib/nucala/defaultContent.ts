/** Keep a stored document usable: fall back to defaults for anything missing or malformed. */
export function normalizeNucala(raw: unknown): NucalaContent {
  const def = buildNucalaDefault();
  if (!raw || typeof raw !== "object") return def;
  const r = raw as Partial<NucalaContent>;
  const nodes = Array.isArray(r.nodes) && r.nodes.length ? r.nodes : def.nodes;
  const start = r.start && nodes.some(x => x.id === r.start) ? r.start : nodes[0].id;
  return {
    schema: 1,
    header: { ...def.header, ...(r.header ?? {}) },
    start,
    sections: Array.isArray(r.sections) && r.sections.length ? r.sections : def.sections,
    fields: Array.isArray(r.fields) ? r.fields : def.fields,
    nodes,
  };
}
