/**
 * One-time edits to documents that were saved before a content change.
 * Saved content wins over the defaults, so a task added in code would never
 * reach a document that is already stored. Each patch runs once per document:
 * its id is recorded in `patches`, so if an admin later deletes the row it
 * is not added back. Patches must be idempotent.
 */
const CONTENT_PATCHES: { id: string; apply: (c: PspContent) => void }[] = [
  {
    id: "ebg-nodir16-extend-plan",
    apply: c => {
      const scr = c.programs.ebglyss.screens.E_NODIR;
      if (!scr) return;
      if (scr.groups.some(g => g.tasks.some(t => t.id === EBG_EXTEND_TASK.id))) return;
      if (scr.groups.length) scr.groups[0].tasks.push({ ...EBG_EXTEND_TASK });
      else scr.groups.push({ id: "g-ebg-nodir16", title: TASKS, right: "", tasks: [{ ...EBG_EXTEND_TASK }] });
    },
  },
];

/**
 * Merge a stored document onto the defaults so that screens / fields added in
 * code later still render. Stored values always win where present.
 */
export function normalizeContent(raw: unknown): PspContent {
  const def = buildDefaultContent();
  if (!raw || typeof raw !== "object") return def;
  const r = raw as Partial<PspContent>;
  const out: PspContent = {
    ...def,
    header: { ...def.header, ...(r.header ?? {}) },
    common: { ...def.common, ...(r.common ?? {}) },
    settings: {
      omvoh: { ...def.settings.omvoh, ...(r.settings?.omvoh ?? {}) },
      qaNewDays: Number.isFinite(r.settings?.qaNewDays) ? Math.max(0, Math.min(365, Number(r.settings?.qaNewDays))) : def.settings.qaNewDays,
    },
    sms: r.sms ?? def.sms,
    qa: Array.isArray(r.qa) ? r.qa : def.qa,
    programs: { ...def.programs },
    patches: Array.isArray(r.patches) ? r.patches : [],
  };
  for (const p of ["omvoh", "ebglyss"] as const) {
    const dp = def.programs[p], rp = r.programs?.[p];
    if (!rp) continue;
    const screens: Record<string, ScreenContent> = {};
    for (const [sid, ds] of Object.entries(dp.screens)) {
      const rs = rp.screens?.[sid];
      screens[sid] = rs ? {
        texts: { ...ds.texts, ...(rs.texts ?? {}) },
        answers: { ...ds.answers, ...(rs.answers ?? {}) },
        groups: Array.isArray(rs.groups) ? rs.groups : ds.groups,
        sms: Array.isArray(rs.sms) ? rs.sms : ds.sms,
      } : ds;
    }
    out.programs[p] = { label: rp.label || dp.label, screens };
  }
  for (const patch of CONTENT_PATCHES) {
    if (out.patches!.includes(patch.id)) continue;
    patch.apply(out);
    out.patches!.push(patch.id);
  }
  return out;
}
